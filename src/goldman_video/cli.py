from .config import GenerationRequest, ShotRequest
from .pipeline import VideoGenerator

app = typer.Typer(help="Goldman AI Video CLI")


def _build_request(
    *,
    prompt: str,
    output: Path,
    frames: int | None,
    duration: int | None,
    width: int,
    height: int,
    resolution: str,
    fps: int,
    watermark: str,
    audio: Path | None,
    audio_start: float,
    audio_volume: float,
    audio_loop: bool,
    image: Path | None = None,
    shots: list[ShotRequest] | None = None,
    gpu: str = "auto",
    low_vram: bool = False,
    precision: str = "fp16",
) -> GenerationRequest:
    req = GenerationRequest(
        prompt=prompt,
        output_path=output,
        num_frames=frames or 120,
        duration_seconds=duration,
        width=width,
        height=height,
        resolution_preset=resolution,
        fps=fps,
        watermark_text=watermark,
        audio_path=audio,
        audio_start_sec=audio_start,
        audio_volume=audio_volume,
        audio_loop=audio_loop,
        image_path=image,
        shots=shots,
        device=gpu,
        low_vram=low_vram,
        precision=precision,
    )
    return req


